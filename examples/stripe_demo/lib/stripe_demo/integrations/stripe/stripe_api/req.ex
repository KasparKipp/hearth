defmodule StripeDemo.Integrations.Stripe.StripeApi.Req do
  @moduledoc """
  Req-based implementation of `StripeDemo.Integrations.Stripe.StripeApi`.

  Generated by Hearth. Each function delegates to the Layer 1
  client's `request/2`.
  """

  @behaviour StripeDemo.Integrations.Stripe.StripeApi

  alias StripeDemo.Integrations.Stripe

  @impl true
  def list_customers(opts \\ []) do
    Stripe.request("/customers", opts)
  end

  @impl true
  def create_customer(opts \\ []) do
    Stripe.request("/customers", [method: :post] ++ opts)
  end

  @impl true
  def get_customer(customer, opts \\ []) do
    Stripe.request("/customers/#{customer}", opts)
  end
end
