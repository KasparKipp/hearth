defmodule StripeDemo.Integrations.Stripe do
  @moduledoc """
  Raw Req client for the Stripe integration.

  Generated by Hearth. `request/2` and `request!/2` perform calls
  against the API — base URL from the OpenAPI spec. `new/1`
  (mirroring `Req.new/1`) builds the underlying configured request.

  ## Credentials

  The credential comes from the `:api_key` option — accepted by
  `new/1`, `request/2` and every function of the behaviour — or else
  from `config :stripe_demo, StripeDemo.Integrations.Stripe, api_key: …`.
  It may be a string, a 0-arity function, or an
  `{module, function, args}` tuple, resolved when each request runs.
  A credential you set explicitly on the request (`auth:`, the
  header, or the query param) is left alone.
  """

  @otp_app :stripe_demo
  @base_url "https://api.stripe.com/v1"

  @doc "Builds a configured Req request — bearer auth. Accepts `Req.new/1` options plus `:api_key`."
  def new(opts \\ []) do
    Req.new(base_url: base_url())
    |> Req.Request.register_options([:api_key])
    |> Req.Request.append_request_steps(put_api_key: &put_api_key/1)
    |> Req.merge(opts)
  end

  @doc """
  Performs a request — returns `{:ok, response}` or `{:error, exception}`.
  `url` may be a type-prefixed id, which stands for its resource's path.
  """
  def request(url, opts \\ []), do: Req.request(new(url: parse_url(url)), opts)

  @doc "Like `request/2`, but raises on error."
  def request!(url, opts \\ []), do: Req.request!(new(url: parse_url(url)), opts)

  defp base_url, do: Application.get_env(@otp_app, __MODULE__, [])[:base_url] || @base_url

  # Runs after Req's own steps, so an explicitly set credential wins.
  defp put_api_key(request) do
    if Req.Request.get_header(request, "authorization") == [],
      do: Req.Request.put_header(request, "authorization", "Bearer " <> credential(request)),
      else: request
  end

  defp credential(request) do
    case request.options[:api_key] || Application.get_env(@otp_app, __MODULE__, [])[:api_key] do
      key when is_binary(key) ->
        key

      fun when is_function(fun, 0) ->
        fun.()

      {module, function, args} ->
        apply(module, function, args)

      nil ->
        raise "missing :api_key for #{inspect(__MODULE__)} — set it in config " <>
                "or pass `api_key:` to new/1, request/2 or a behaviour function"
    end
  end

  # A type-prefixed id stands for its resource's path:
  # `"cus_123"` → `"/customers/cus_123"`. Anything after
  # the id comes along; any other URL passes through.
  defp parse_url("cus_" <> _ = id), do: "/customers/#{id}"
  defp parse_url(url), do: url
end
