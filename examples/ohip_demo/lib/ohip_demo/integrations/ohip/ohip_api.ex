defmodule OhipDemo.Integrations.Ohip.OhipApi do
  @moduledoc """
  Behaviour for the Ohip HTTP integration.

  Generated by Hearth from an OpenAPI spec — one callback per
  operation. Business logic should depend on this behaviour rather
  than calling HTTP directly.

  ## Source

  * **Source:** `blk: ohip_blk@26.2, evm: ohip_evm@26.2`
  * **Title:** OPERA Cloud Block API + OPERA Cloud Sales Event Management API
  * **Version:** 26.2.0.0
  * **OpenAPI:** 3.0.3
  """

  @otp_app :ohip_demo

  @callback get_blocks(opts :: keyword()) :: {:ok, Req.Response.t()} | {:error, Exception.t()}

  @doc """
  Get Blocks

  Use this API to retrieve a list of blocks for requested query parameters. A wide range of query parameters is available to support various persona requirements, so it is recommended to include, at least, the hotel block date range, stay date range, and/or number of days as query parameters. You can use more query parameters to narrow your results. This API is not designed to support sync between two systems or initial upload of data. If x-hubid is used as a header, it returns matching data from multiple hotels within the same chain. <p><strong>OperationId:</strong>getBlocks</p> <p>The maximum allowable limit for this API is <strong>200</strong>.</p>
  """
  def get_blocks(opts \\ []), do: impl().get_blocks(opts)

  @callback get_block(block_id :: String.t(), hotel_id :: String.t(), opts :: keyword()) ::
              {:ok, Req.Response.t()} | {:error, Exception.t()}

  @doc """
  Get a Block By ID

  Use this API to retrieve a specific block.  You will need to know the blockID in the request; if you don't know it, please go ahead and use getBlocks API first.  The response will include detailed information about the block. <p><strong>OperationId:</strong>getBlock</p>
  """
  def get_block(block_id, hotel_id, opts \\ []), do: impl().get_block(block_id, hotel_id, opts)

  @callback get_block_range_info(
              block_id :: String.t(),
              hotel_id :: String.t(),
              opts :: keyword()
            ) :: {:ok, Req.Response.t()} | {:error, Exception.t()}

  @doc """
  Get Block Range Information

  Request for updating block allocation for a range of dates. <p><strong>OperationId:</strong>getBlockRangeInfo</p>
  """
  def get_block_range_info(block_id, hotel_id, opts \\ []),
    do: impl().get_block_range_info(block_id, hotel_id, opts)

  @callback get_block_room_rate_grid(
              block_id :: String.t(),
              hotel_id :: String.t(),
              opts :: keyword()
            ) :: {:ok, Req.Response.t()} | {:error, Exception.t()}

  @doc """
  Operation to get room rate grid for a Block and supports pagination.

  Use this API to retrieve grid details for a specific block. The response will include detailed information about the block grid and response can be paginated for blocks with longer date range.. <p><strong>OperationId:</strong>getBlockRoomRateGrid</p>
  """
  def get_block_room_rate_grid(block_id, hotel_id, opts \\ []),
    do: impl().get_block_room_rate_grid(block_id, hotel_id, opts)

  @callback get_event_calendar(hotel_id :: String.t(), opts :: keyword()) ::
              {:ok, Req.Response.t()} | {:error, Exception.t()}

  @doc """
  Get the event calendar

  You will be able to retrieve all events on the calendar for a specified property.  Narrow the results down by using the available parameters, such as Event Status, Event eventStartDate date, Location, Number of Attendees and so on. <p><strong>OperationId:</strong>getEventCalendar</p> <p>This API allows a time span of <strong>21</strong> days.</p>
  """
  def get_event_calendar(hotel_id, opts \\ []), do: impl().get_event_calendar(hotel_id, opts)

  @callback get_events_one_hotel(hotel_id :: String.t(), opts :: keyword()) ::
              {:ok, Req.Response.t()} | {:error, Exception.t()}

  @doc """
  Get Events

  This API fetches catering events for a specific hotel, based on search criteria such as dates, linked block, status, function space, and more. The data returned in the result contains, event type, description, dates and times, attendees, function space, setup style and more. <p><strong>OperationId:</strong>getEventsOneHotel</p> <p>The maximum allowable limit for this API is <strong>200</strong>.</p> <p>This API allows a time span of <strong>90</strong> days.</p>
  """
  def get_events_one_hotel(hotel_id, opts \\ []), do: impl().get_events_one_hotel(hotel_id, opts)

  @callback get_event(event_id :: String.t(), hotel_id :: String.t(), opts :: keyword()) ::
              {:ok, Req.Response.t()} | {:error, Exception.t()}

  @doc """
  Get an Event

  This API will allow you to retrieve the details of one event by specifying the event ID in the path. Event details such as event type, event description, start date / time and end date time, attendees, function space, setup style, function space rate, and more  will be returned. You can also add fetch instructions to specify what additional event data, such as block information, revenue information, event notes, and master / sub event information you would like returned in the response. If you don't know the eventID, please use getEvents API to find the event and it's respective eventID. <p><strong>OperationId:</strong>getEvent</p>
  """
  def get_event(event_id, hotel_id, opts \\ []), do: impl().get_event(event_id, hotel_id, opts)

  defp impl, do: Application.get_env(@otp_app, __MODULE__, [])[:impl] || __MODULE__.Req
end
