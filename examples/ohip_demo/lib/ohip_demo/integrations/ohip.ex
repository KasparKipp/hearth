defmodule OhipDemo.Integrations.Ohip do
  @moduledoc """
  Raw Req client for the Ohip integration.

  Generated by Hearth. `request/2` and `request!/2` perform calls
  against the API — base URL from `OhipDemo.Tenancy.gateway/1`, given `:chain`. `new/1`
  (mirroring `Req.new/1`) builds the underlying configured request.

  ## Credentials

  The credential comes from the `:api_key` option — accepted by
  `new/1`, `request/2` and every function of the behaviour — or else
  from `OhipDemo.Tenancy.token/1`, given `:chain`, called when each
  request runs. It is never read from config.
  A credential you set explicitly on the request (`auth:`, the
  header, or the query param) is left alone.

  ## Headers

  Every request sends:

    * `x-app-key` — `OhipDemo.Tenancy.app_key/1`, given `:chain`
    * `x-hotelid` — the `:hotel_id` option

  An option is accepted by `new/1`, `request/2` and every function of
  the behaviour. Config means `config :ohip_demo, OhipDemo.Integrations.Ohip, …`.
  An option or config value may be a string, a 0-arity function, or an
  `{module, function, args}` tuple; a resolver must return a string.
  Each is resolved when the request runs. A header you set on the
  request yourself is left alone.

  ## Base URL

  The base URL comes from `OhipDemo.Tenancy.gateway/1`, given `:chain`, when each request runs. A
  `base_url:` passed to `new/1`, `request/2` or a behaviour function is
  used as is.
  """

  @doc "Builds a configured Req request — bearer auth. Accepts `Req.new/1` options plus `:api_key`, `:chain`, `:hotel_id`."
  def new(opts \\ []) do
    Req.new()
    |> Req.Request.register_options([:api_key, :chain, :hotel_id])
    |> Req.Request.prepend_request_steps(resolve_base_url: &resolve_base_url/1)
    |> Req.Request.append_request_steps(put_api_key: &put_api_key/1, put_headers: &put_headers/1)
    |> Req.merge(opts)
  end

  @doc "Performs a request — returns `{:ok, response}` or `{:error, exception}`."
  def request(url, opts \\ []), do: Req.request(new(url: url), opts)

  @doc "Like `request/2`, but raises on error."
  def request!(url, opts \\ []), do: Req.request!(new(url: url), opts)

  # Runs before Req's own steps; a `base_url:` passed per call wins, as is.
  defp resolve_base_url(request) do
    if request.options[:base_url],
      do: request,
      else:
        Req.Request.put_option(
          request,
          :base_url,
          resolved!(
            OhipDemo.Tenancy.gateway(resolver_options(request, [:chain])),
            "OhipDemo.Tenancy.gateway/1 (the base URL)"
          )
        )
  end

  # Runs after Req's own steps, so an explicitly set credential wins.
  defp put_api_key(request) do
    if Req.Request.get_header(request, "authorization") == [],
      do: Req.Request.put_header(request, "authorization", "Bearer " <> credential(request)),
      else: request
  end

  defp credential(request) do
    case request.options[:api_key] do
      nil ->
        resolved!(
          OhipDemo.Tenancy.token(resolver_options(request, [:chain])),
          "OhipDemo.Tenancy.token/1"
        )

      key when is_binary(key) ->
        key

      fun when is_function(fun, 0) ->
        fun.()

      {module, function, args} ->
        apply(module, function, args)
    end
  end

  @headers ["x-app-key", "x-hotelid"]

  # Runs after Req's own steps, so a header already on the request wins.
  defp put_headers(request) do
    Enum.reduce(@headers, request, fn name, request ->
      if Req.Request.get_header(request, name) == [],
        do: Req.Request.put_header(request, name, header_value(request, name)),
        else: request
    end)
  end

  # x-app-key: `OhipDemo.Tenancy.app_key/1`, given `:chain`.
  defp header_value(request, "x-app-key") do
    resolved!(
      OhipDemo.Tenancy.app_key(resolver_options(request, [:chain])),
      "OhipDemo.Tenancy.app_key/1 (the x-app-key header)"
    )
  end

  # x-hotelid: the `:hotel_id` option.
  defp header_value(request, "x-hotelid") do
    case request.options[:hotel_id] do
      value when is_binary(value) ->
        value

      fun when is_function(fun, 0) ->
        fun.()

      {module, function, args} ->
        apply(module, function, args)

      nil ->
        raise "missing :hotel_id for #{inspect(__MODULE__)} (the x-hotelid header) — " <>
                "pass `hotel_id:` to new/1, request/2 or a behaviour function"
    end
  end

  # The request options a resolver is given.
  defp resolver_options(request, keys), do: request.options |> Map.take(keys) |> Map.to_list()

  # A resolver must return a string. The value isn't shown, in case
  # it's a secret.
  defp resolved!(value, _resolver) when is_binary(value), do: value

  defp resolved!(_value, resolver),
    do: raise("#{resolver} returned no string for #{inspect(__MODULE__)}")
end
