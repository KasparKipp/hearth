defmodule Hearth.Render.Layer2 do
  @moduledoc false

  # Renders the Layer 2 behaviour module — the contract every callsite
  # depends on. One `@callback` per selected operation.
  #
  # Function shape (per the CLAUDE.md three-layer pattern):
  #
  #   * path params become positional args, in spec order, named with
  #     the snake_case-sanitized param name, typed `String.t()`;
  #   * query and body params funnel through a final `opts :: keyword()`;
  #   * every callback returns the generic
  #     `{:ok, Req.Response.t()} | {:error, Exception.t()}` — typed
  #     response structs from schemas are a later concern.
  #
  # The module is assembled as a string and run through
  # `Code.format_string!/1`: it normalizes layout and raises on any
  # syntax error, so a malformed render fails loudly in tests.

  alias Hearth.Spec.Operation

  @return_type "{:ok, Req.Response.t()} | {:error, Exception.t()}"

  @spec render(module(), [Operation.t()]) :: String.t()
  def render(module, operations) when is_list(operations) do
    """
    defmodule #{inspect(module)} do
      @moduledoc \"\"\"
      Behaviour for the #{integration_label(module)} HTTP integration.

      Generated by Hearth from an OpenAPI spec — one callback per
      operation. Business logic should depend on this behaviour rather
      than calling HTTP directly.
      \"\"\"

      #{Enum.map_join(operations, "\n\n", &callback/1)}
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp callback(%Operation{} = op) do
    callback_doc(op) <> "@callback #{op.id}(#{arg_signature(op)}) :: #{@return_type}"
  end

  defp callback_doc(%Operation{summary: summary}) when is_binary(summary) and summary != "" do
    ~s(@doc "#{escape(summary)}"\n)
  end

  defp callback_doc(_op), do: ""

  defp arg_signature(%Operation{path_params: params}) do
    path_args = Enum.map(List.wrap(params), &"#{param_name(&1)} :: String.t()")
    Enum.join(path_args ++ ["opts :: keyword()"], ", ")
  end

  defp param_name(param) when is_map(param) do
    Operation.sanitize_id(param["name"] || "param")
  end

  defp escape(string) do
    string
    |> String.replace("\\", "\\\\")
    |> String.replace("\"", "\\\"")
    |> String.replace("\n", " ")
  end

  defp integration_label(module) do
    module
    |> Module.split()
    |> List.last()
    |> String.replace_suffix("Api", "")
  end
end
