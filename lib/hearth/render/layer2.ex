defmodule Hearth.Render.Layer2 do
  @moduledoc false

  # Renders the Layer 2 behaviour module — the contract every callsite
  # depends on. One `@callback` per selected operation.
  #
  # Function shape (per the CLAUDE.md three-layer pattern):
  #
  #   * path params become positional args, in spec order, named with
  #     the snake_case-sanitized param name, typed `String.t()`;
  #   * query and body params funnel through a final `opts :: keyword()`;
  #   * every callback returns the generic
  #     `{:ok, Req.Response.t()} | {:error, Exception.t()}` — typed
  #     response structs from schemas are a later concern;
  #   * the operation's `summary` and `description` become a `@doc`
  #     heredoc on the callback — summary first, description below.
  #
  # The moduledoc closes with a markdown metadata footer — the source
  # the integration was generated from, plus the spec's `info` fields.
  #
  # The module is assembled as a string and run through
  # `Code.format_string!/1`: it normalizes layout and raises on any
  # syntax error, so a malformed render fails loudly in tests.

  alias Hearth.Spec.Operation

  @return_type "{:ok, Req.Response.t()} | {:error, Exception.t()}"

  @spec render(module(), [Operation.t()], map()) :: String.t()
  def render(module, operations, metadata \\ %{}) when is_list(operations) do
    """
    defmodule #{inspect(module)} do
      @moduledoc \"\"\"
      #{moduledoc(module, metadata)}
      \"\"\"

      #{Enum.map_join(operations, "\n\n", &callback/1)}
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp moduledoc(module, metadata) do
    intro = """
    Behaviour for the #{integration_label(module)} HTTP integration.

    Generated by Hearth from an OpenAPI spec — one callback per
    operation. Business logic should depend on this behaviour rather
    than calling HTTP directly.\
    """

    intro <> metadata_section(metadata)
  end

  # A markdown metadata footer for the moduledoc: where the integration
  # was generated from (`:source` — a file path or URL), plus the
  # spec's `info` fields. Omitted entirely when no metadata is given.
  defp metadata_section(metadata) do
    fields =
      [
        {"Source", backtick(clean(metadata[:source]))},
        {"Title", clean(metadata[:title])},
        {"Version", clean(metadata[:version])},
        {"OpenAPI", clean(metadata[:openapi])}
      ]
      |> Enum.reject(fn {_label, value} -> is_nil(value) end)

    description = clean(metadata[:description])

    if fields == [] and is_nil(description) do
      ""
    else
      body =
        [bullets(fields), description]
        |> Enum.reject(&(&1 in [nil, ""]))
        |> Enum.join("\n\n")

      "\n\n## Source\n\n" <> body
    end
  end

  defp bullets(fields) do
    Enum.map_join(fields, "\n", fn {label, value} -> "* **#{label}:** #{value}" end)
  end

  defp backtick(nil), do: nil
  defp backtick(value), do: "`#{value}`"

  defp clean(nil), do: nil

  defp clean(value) do
    case value |> to_string() |> String.trim() do
      "" -> nil
      text -> normalize(text)
    end
  end

  defp callback(%Operation{} = op) do
    callback_doc(op) <> "@callback #{op.id}(#{arg_signature(op)}) :: #{@return_type}"
  end

  # The operation's summary on the first line, its longer description
  # below it (a blank line between). Either may be absent; with neither,
  # no @doc is emitted. Rendered as a heredoc so multi-paragraph
  # descriptions keep their shape.
  defp callback_doc(%Operation{} = op) do
    case doc_body(op) do
      nil -> ""
      body -> ~s(@doc """\n#{body}\n"""\n)
    end
  end

  defp doc_body(%Operation{summary: summary, description: description}) do
    [summary, description]
    |> Enum.map(&normalize/1)
    |> Enum.reject(&(&1 == ""))
    |> Enum.join("\n\n")
    |> case do
      "" -> nil
      body -> body
    end
  end

  defp arg_signature(%Operation{path_params: params}) do
    path_args = Enum.map(List.wrap(params), &"#{param_name(&1)} :: String.t()")
    Enum.join(path_args ++ ["opts :: keyword()"], ", ")
  end

  defp param_name(param) when is_map(param) do
    Operation.sanitize_id(param["name"] || "param")
  end

  # Escapes the two sequences that would break a generated heredoc: a
  # backslash, and the interpolation opener. A lone `"""` line would
  # also terminate it early — vanishingly rare in OpenAPI prose, left
  # unhandled. Backslash must be escaped before the interpolation
  # opener, so the backslash this adds is not itself doubled.
  defp normalize(text) when is_binary(text) do
    text
    |> String.trim()
    |> String.replace("\\", "\\\\")
    |> String.replace("\#{", "\\\#{")
  end

  defp normalize(_), do: ""

  defp integration_label(module) do
    module
    |> Module.split()
    |> List.last()
    |> String.replace_suffix("Api", "")
  end
end
