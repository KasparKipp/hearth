defmodule Hearth.Render.Tests do
  @moduledoc false

  # Renders test files for a generated integration. Two:
  #
  #   * `layer1/4` — the Layer 1 auth test, a `Req.Test`-plug ExUnit
  #     module that asserts the auth scheme attaches the right
  #     credential at request time;
  #   * `external/6` — an `:external`-tagged scaffold of real HTTP calls
  #     against the live API, one `test` per operation. Generated once
  #     and never overwritten — the user carries on from it.
  #
  # The test runs through the real `request!/2` entry point. Because
  # `request!/2` does not thread caller opts into `new/1`, the
  # credential is seeded into application env in `setup` — which is
  # process-global, hence `async: false`.
  #
  # The `plug:` option routes the request to an in-process plug; the
  # assertion runs inside it. Assembled as a string and run through
  # `Code.format_string!/1`.
  #
  # The whole module is wrapped in `if Code.ensure_loaded?(Plug.Conn)`
  # so the file compiles even when the consumer has no `plug` dep. The
  # gen task does not add `plug`: `req` already declares it as an
  # optional all-environment dependency, so a consumer dep scoped
  # `only: :test` would diverge from that and break the build.

  alias Hearth.Spec.Auth
  alias Hearth.Spec.Operation

  @api_key "hearth-test-credential"

  @spec layer1(module(), module(), atom(), Auth.strategy()) :: String.t()
  def layer1(test_module, client_module, otp_app, auth) do
    """
    # This test drives `Req.Test` through Plug; it is active only when
    # `plug` is loaded. To run it, add `{:plug, "~> 1.0"}` to your deps
    # — for all environments, not `only: :test`: `req` declares `plug`
    # as an optional all-environment dependency, and a narrower scope
    # diverges from it.
    if Code.ensure_loaded?(Plug.Conn) do
      defmodule #{inspect(test_module)} do
        @moduledoc false

        # Generated by Hearth — verifies the auth scheme wired into
        # #{inspect(client_module)} attaches credentials at request time.
        # Hearth-owned: regenerated on every `mix hearth.gen` run.

        use ExUnit.Case, async: false

        @client #{inspect(client_module)}
        @api_key #{inspect(@api_key)}

        #{setup_block(auth, otp_app)}
        #{auth_test(auth, client_module)}
      end
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  # Bearer and API-key auth read a credential; seed it into app config.
  # `Keyword.put` into the *existing* config rather than `put_env` of a
  # bare list — `put_env` replaces the whole keyword, which would wipe
  # a `:base_url` set by `config/test.exs`. `on_exit` restores the
  # previous value exactly (no `delete_env`, which has the same wipe).
  defp setup_block(:bearer, otp_app), do: credential_setup(otp_app)
  defp setup_block({:api_key, _location, _name}, otp_app), do: credential_setup(otp_app)
  defp setup_block(_auth, _otp_app), do: ""

  defp credential_setup(otp_app) do
    """
    setup do
      previous = Application.get_env(#{inspect(otp_app)}, @client, [])
      Application.put_env(#{inspect(otp_app)}, @client, Keyword.put(previous, :api_key, @api_key))
      on_exit(fn -> Application.put_env(#{inspect(otp_app)}, @client, previous) end)
      :ok
    end
    """
  end

  defp auth_test(:bearer, _client) do
    test_block(
      "request! attaches a bearer token from config",
      ~s|assert Plug.Conn.get_req_header(conn, "authorization") == ["Bearer \#{@api_key}"]|
    )
  end

  defp auth_test({:api_key, :header, name}, _client) do
    test_block(
      "request! sets the #{name} header from config",
      ~s|assert Plug.Conn.get_req_header(conn, #{inspect(String.downcase(name))}) == [@api_key]|
    )
  end

  defp auth_test({:api_key, :query, name}, _client) do
    test_block("request! sets the #{name} query param from config", """
    conn = Plug.Conn.fetch_query_params(conn)
    assert conn.query_params[#{inspect(name)}] == @api_key
    """)
  end

  defp auth_test(:none, _client) do
    test_block(
      "request! sends no authorization header",
      ~s|assert Plug.Conn.get_req_header(conn, "authorization") == []|
    )
  end

  defp auth_test({:unsupported, type}, client) do
    """
    # TODO: #{type} auth is not auto-wired — see the TODO in
    # #{inspect(client)}. Add auth assertions here once it is wired.
    test "request! reaches the API (auth not wired)" do
      plug = fn conn -> Plug.Conn.send_resp(conn, 200, JSON.encode!(%{})) end

      assert %Req.Response{status: 200} = @client.request!("/ping", plug: plug)
    end
    """
  end

  # An ExUnit test that asserts on the request inside a `Req.Test` plug.
  # `plug_body` is one or more lines operating on `conn`.
  defp test_block(name, plug_body) do
    """
    test #{inspect(name)} do
      plug = fn conn ->
        #{String.trim_trailing(plug_body)}
        Plug.Conn.send_resp(conn, 200, JSON.encode!(%{}))
      end

      assert %Req.Response{status: 200} = @client.request!("/ping", plug: plug)
    end
    """
  end

  @doc """
  Renders the external integration test — a scaffold of real HTTP calls.

  One `test` per operation, calling Layer 3 (`<Layer2>.Req.<op>`)
  directly: Layer 2's dispatcher routes to the Mox mock in `:test`, so
  the external test bypasses it to reach the network. Tagged
  `:external`. Generated once and never overwritten — `mix hearth.gen`
  writes it with `on_exists: :skip`.
  """
  @spec external(module(), module(), module(), atom(), Auth.strategy(), [Operation.t()]) ::
          String.t()
  def external(test_module, layer2, layer1, otp_app, auth, operations) do
    alias_name = layer2 |> Module.split() |> List.last()

    """
    defmodule #{inspect(test_module)} do
      @moduledoc false

      # Generated once by Hearth — a scaffold for real HTTP calls
      # against the live API. Hearth never overwrites this file; edit
      # it freely. Tagged `:external` and skipped by `mix test` — run
      # it with `mix test --include external`.

      use ExUnit.Case, async: #{external_async(auth)}

      @moduletag :external

      alias #{inspect(layer2)}
      #{external_setup(auth, otp_app, layer1)}
      #{Enum.map_join(operations, "\n\n", &external_op_test(&1, alias_name))}
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp external_async(:bearer), do: "false"
  defp external_async({:api_key, _location, _name}), do: "false"
  defp external_async(_auth), do: "true"

  # Credentialed auth needs the key seeded into app config: `:test` env
  # has none (`config/runtime.exs` only sets it for prod/dev).
  defp external_setup(:bearer, otp_app, layer1), do: external_credential_setup(otp_app, layer1)

  defp external_setup({:api_key, _location, _name}, otp_app, layer1),
    do: external_credential_setup(otp_app, layer1)

  defp external_setup(_auth, _otp_app, _layer1), do: ""

  defp external_credential_setup(otp_app, layer1) do
    env_var =
      (layer1 |> Module.split() |> List.last() |> Macro.underscore() |> String.upcase()) <>
        "_API_KEY"

    """
    @client #{inspect(layer1)}

    setup do
      # Merge into the existing config — `config/test.exs` sets a
      # `:base_url` on @client; a bare `put_env` would wipe it and the
      # external test would hit production.
      previous = Application.get_env(#{inspect(otp_app)}, @client, [])
      api_key = System.get_env(#{inspect(env_var)}) || #{inspect("DEV_NO_" <> env_var)}
      Application.put_env(#{inspect(otp_app)}, @client, Keyword.put(previous, :api_key, api_key))
      on_exit(fn -> Application.put_env(#{inspect(otp_app)}, @client, previous) end)
      :ok
    end
    """
  end

  defp external_op_test(%Operation{} = op, alias_name) do
    """
    # TODO: replace the placeholder args/opts and assert on your use-case.
    test "#{op.id} reaches the live API" do
      assert {:ok, %Req.Response{}} = #{alias_name}.Req.#{op.id}(#{external_call_args(op)})
    end
    """
    |> String.trim_trailing()
  end

  defp external_call_args(%Operation{path_params: params}) do
    path_args = params |> List.wrap() |> Enum.map(fn _ -> ~s("TODO") end)
    Enum.join(path_args ++ ["[]"], ", ")
  end
end
