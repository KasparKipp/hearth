defmodule Hearth.Render.Layer3 do
  @moduledoc false

  # Renders the Layer 3 implementation — the Req-based module that
  # satisfies the Layer 2 behaviour. One function per operation, each
  # delegating to a private `request/3` helper that builds the call
  # through the Layer 1 raw client.
  #
  # Path params interpolate into the URL: each `{rawName}` in the spec
  # path becomes `#{sanitized_name}`, the same arg name Layer 2's
  # signature uses. Query and body params ride through `opts` straight
  # into `Req.request/2`, so the function bodies are uniform regardless
  # of operation shape — pure plumbing.
  #
  # Assembled as a string and run through `Code.format_string!/1`.

  alias Hearth.Spec.Operation

  @spec render(module(), module(), module(), [Operation.t()]) :: String.t()
  def render(layer3, layer2, layer1, operations) when is_list(operations) do
    client = layer1 |> Module.split() |> List.last()

    """
    defmodule #{inspect(layer3)} do
      @moduledoc \"\"\"
      Req-based implementation of `#{inspect(layer2)}`.

      Generated by Hearth. Each function delegates to the Layer 1 raw
      client and dispatches the request through Req.
      \"\"\"

      @behaviour #{inspect(layer2)}

      alias #{inspect(layer1)}

      #{Enum.map_join(operations, "\n\n", &impl_fun/1)}

      defp request(method, url, opts) do
        #{client}.client() |> Req.request([method: method, url: url] ++ opts)
      end
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp impl_fun(%Operation{} = op) do
    """
    @impl true
    def #{op.id}(#{def_args(op)}), do: request(#{inspect(op.method)}, #{url_literal(op)}, opts)
    """
    |> String.trim_trailing()
  end

  defp def_args(%Operation{path_params: params}) do
    path_args = params |> List.wrap() |> Enum.map(&param_arg/1)
    Enum.join(path_args ++ ["opts \\\\ []"], ", ")
  end

  defp param_arg(param) when is_map(param) do
    Operation.sanitize_id(param["name"] || "param")
  end

  # Builds the URL string literal, interpolating each path param.
  # `/pets/{petId}` with param `petId` → the literal `"/pets/#{pet_id}"`.
  defp url_literal(%Operation{path: path, path_params: params}) do
    interpolated =
      params
      |> List.wrap()
      |> Enum.reduce(path, fn param, acc ->
        raw = param["name"]
        String.replace(acc, "{#{raw}}", "\#{#{Operation.sanitize_id(raw)}}")
      end)

    "\"" <> interpolated <> "\""
  end
end
