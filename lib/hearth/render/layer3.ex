defmodule Hearth.Render.Layer3 do
  @moduledoc false

  # Renders the Layer 3 implementation — the Req-based module that
  # satisfies the Layer 2 behaviour. One function per operation, each
  # delegating to the Layer 1 client's `request/2` — never `new/1` or
  # `Req` directly. Layer 1 owns all HTTP machinery.
  #
  # Path params interpolate into the URL: each `{rawName}` in the spec
  # path becomes `#{sanitized_name}`, the same arg name Layer 2's
  # signature uses. `:get` is Req's default method, so it is left
  # unspecified; any other verb prepends `method:` to `opts`. Query and
  # body params ride through `opts` straight into `<Client>.request/2`,
  # so the function bodies are uniform — pure plumbing.
  #
  # Assembled as a string and run through `Code.format_string!/1`.

  alias Hearth.Spec.Operation

  @spec render(module(), module(), module(), [Operation.t()]) :: String.t()
  def render(layer3, layer2, layer1, operations) when is_list(operations) do
    client = layer1 |> Module.split() |> List.last()

    """
    defmodule #{inspect(layer3)} do
      @moduledoc \"\"\"
      Req-based implementation of `#{inspect(layer2)}`.

      Generated by Hearth. Each function delegates to the Layer 1
      client's `request/2`.
      \"\"\"

      @behaviour #{inspect(layer2)}

      alias #{inspect(layer1)}

      #{Enum.map_join(operations, "\n\n", &impl_fun(&1, client))}
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp impl_fun(%Operation{} = op, client) do
    """
    @impl true
    def #{op.id}(#{def_args(op)}) do
      #{client}.request(#{url_literal(op)}#{request_opts(op)})
    end
    """
    |> String.trim_trailing()
  end

  # `:get` is Req's default — leave the method unspecified for it.
  defp request_opts(%Operation{method: :get}), do: ", opts"
  defp request_opts(%Operation{method: method}), do: ", [method: #{inspect(method)}] ++ opts"

  defp def_args(%Operation{} = op) do
    Enum.join(Operation.path_args(op) ++ ["opts \\\\ []"], ", ")
  end

  # Builds the URL string literal, interpolating each path param.
  # `/pets/{petId}` with param `petId` → the literal `"/pets/#{pet_id}"`.
  # One pass over the template: substituting param by param would let
  # a later `{pet_id}` match inside an earlier inserted `#{pet_id}`.
  defp url_literal(%Operation{path: path, path_params: params} = op) do
    arg_for =
      params
      |> List.wrap()
      |> Enum.zip(Operation.path_args(op))
      |> Map.new(fn {param, arg} -> {param["name"], arg} end)

    interpolated =
      Regex.replace(~r/\{([^}]+)\}/, path, fn template, name ->
        case Map.fetch(arg_for, name) do
          {:ok, arg} -> "\#{#{arg}}"
          :error -> template
        end
      end)

    "\"" <> interpolated <> "\""
  end
end
