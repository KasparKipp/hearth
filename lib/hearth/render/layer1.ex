defmodule Hearth.Render.Layer1 do
  @moduledoc false

  # Renders the Layer 1 raw Req client. Its public API:
  #
  #   * `new/1`      — builds a configured `%Req.Request{}` (base URL,
  #                    auth, plus any passed opts), mirroring `Req.new/1`;
  #   * `request/2`  — performs a call, `{:ok, resp} | {:error, exc}`;
  #   * `request!/2` — same, raising on error.
  #
  # Layer 3 (the behaviour implementation) dispatches through
  # `request/2` — it never touches `new/1` or `Req` directly.
  #
  # The base URL is read from application config keyed by the client
  # module itself — `config :<otp_app>, <ClientModule>, base_url: "…"` —
  # falling back to the `@base_url` compiled from the spec.
  #
  # Auth is rendered from the spec's security scheme:
  #
  #   * `:bearer`               → an `authorization: Bearer …` header
  #   * `{:api_key, :header, n}` → a request header
  #   * `{:api_key, :query, n}`  → a query parameter
  #   * `:none`                 → base URL only
  #   * `{:unsupported, type}`  → base URL only, plus a TODO comment
  #
  # Keyed schemes attach the credential in a Req request step
  # (`put_api_key/1`), appended so it runs after Req's own `auth` and
  # `put_params` steps:
  #
  #   * `:api_key` is a registered option, so it is accepted by `new/1`,
  #     `request/2` and — through their `opts` — Layers 2 and 3;
  #   * the credential is resolved when each request runs, from the
  #     `:api_key` option or else `config … api_key:`, and may be a
  #     string, a 0-arity fun or an `{m, f, a}` tuple;
  #   * a credential the caller set explicitly (`auth:`, the header, or
  #     the query param) is left alone;
  #   * the query key goes straight into the URL, never through
  #     `:params`, so it cannot collide with the caller's params.
  #
  # Assembled as a string and run through `Code.format_string!/1`.

  alias Hearth.Spec.Auth

  @spec render(module(), atom(), String.t() | nil, String.t(), Auth.strategy(), map() | nil) ::
          String.t()
  def render(module, otp_app, base_url, path_prefix, auth, prefixed \\ nil) do
    """
    defmodule #{inspect(module)} do
      @moduledoc \"\"\"
      Raw Req client for the #{label(module)} integration.

      Generated by Hearth. `request/2` and `request!/2` perform calls
      against the API — base URL from the OpenAPI spec. `new/1`
      (mirroring `Req.new/1`) builds the underlying configured request.#{credentials_doc(module, otp_app, auth)}
      \"\"\"

      @otp_app #{inspect(otp_app)}
      #{base_url_attr(base_url, path_prefix)}

      #{new_fun(auth)}
      #{Hearth.Render.PrefixedIds.request_funs(prefixed) || request_funs()}#{base_url_helper()}#{auth_step(auth)}#{Hearth.Render.PrefixedIds.layer1(prefixed)}
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  # A path prefix shared by every operation (e.g. `/v3`) is folded into
  # the base URL here — onto the real URL when the spec declares one,
  # onto the placeholder when it does not, so the prefix is never lost.
  defp base_url_attr(nil, prefix) do
    ~s(# TODO: the spec declared no `servers` — set the API base URL.\n) <>
      ~s(  @base_url "https://api.example.com#{prefix}")
  end

  defp base_url_attr(url, prefix), do: ~s(@base_url #{inspect(append_prefix(url, prefix))})

  defp append_prefix(url, ""), do: url
  defp append_prefix(url, prefix), do: String.trim_trailing(url, "/") <> prefix

  defp new_fun(:bearer), do: keyed_new("bearer auth")
  defp new_fun({:api_key, :header, _name}), do: keyed_new("API-key header")
  defp new_fun({:api_key, :query, _name}), do: keyed_new("API-key query param")

  defp new_fun(:none) do
    """
    @doc "Builds a configured Req request for the API."
    def new(opts \\\\ []) do
      Req.new(base_url: base_url()) |> Req.merge(opts)
    end
    """
  end

  defp new_fun({:unsupported, type}) do
    """
    # TODO: the spec uses #{inspect(type)} auth, which Hearth does not
    # generate automatically. Wire it as a Req request step — see
    # https://hexdocs.pm/req/Req.Steps.html
    @doc "Builds a configured Req request — auth not wired (see TODO above)."
    def new(opts \\\\ []) do
      Req.new(base_url: base_url()) |> Req.merge(opts)
    end
    """
  end

  defp keyed_new(label) do
    """
    @doc "Builds a configured Req request — #{label}. Accepts `Req.new/1` options plus `:api_key`."
    def new(opts \\\\ []) do
      Req.new(base_url: base_url())
      |> Req.Request.register_options([:api_key])
      |> Req.Request.append_request_steps(put_api_key: &put_api_key/1)
      |> Req.merge(opts)
    end
    """
  end

  defp request_funs do
    """
    @doc "Performs a request — returns `{:ok, response}` or `{:error, exception}`."
    def request(url, opts \\\\ []), do: Req.request(new(url: url), opts)

    @doc "Like `request/2`, but raises on error."
    def request!(url, opts \\\\ []), do: Req.request!(new(url: url), opts)
    """
  end

  # The base URL is config-overridable (`config :<otp_app>, <Client>,
  # base_url: "…"`), defaulting to the spec-derived `@base_url`. Lets
  # `config/test.exs` point the external test at a non-prod server.
  defp base_url_helper do
    """

    defp base_url, do: Application.get_env(@otp_app, __MODULE__, [])[:base_url] || @base_url
    """
  end

  # Indented to sit inside the moduledoc heredoc.
  defp credentials_doc(_module, _otp_app, auth)
       when auth == :none or elem(auth, 0) == :unsupported,
       do: ""

  defp credentials_doc(module, otp_app, _auth) do
    """


    ## Credentials

    The credential comes from the `:api_key` option — accepted by
    `new/1`, `request/2` and every function of the behaviour — or else
    from `config #{inspect(otp_app)}, #{inspect(module)}, api_key: …`.
    It may be a string, a 0-arity function, or an
    `{module, function, args}` tuple, resolved when each request runs.
    A credential you set explicitly on the request (`auth:`, the
    header, or the query param) is left alone.
    """
    |> String.trim_trailing()
    |> String.replace(~r/^(?=.)/m, "  ")
  end

  defp auth_step(:bearer) do
    put_api_key("""
    if Req.Request.get_header(request, "authorization") == [],
      do: Req.Request.put_header(request, "authorization", "Bearer " <> credential(request)),
      else: request
    """)
  end

  defp auth_step({:api_key, :header, name}) do
    header = inspect(String.downcase(name))

    put_api_key("""
    if Req.Request.get_header(request, #{header}) == [],
      do: Req.Request.put_header(request, #{header}, credential(request)),
      else: request
    """)
  end

  defp auth_step({:api_key, :query, name}) do
    put_api_key("""
    query = request.url.query || ""

    if Map.has_key?(URI.decode_query(query), #{inspect(name)}) do
      request
    else
      param = URI.encode_query([{#{inspect(name)}, credential(request)}])
      put_in(request.url.query, Enum.join(Enum.reject([query, param], &(&1 == "")), "&"))
    end
    """)
  end

  defp auth_step(_auth), do: ""

  defp put_api_key(body) do
    """

    # Runs after Req's own steps, so an explicitly set credential wins.
    defp put_api_key(request) do
      #{body}
    end

    defp credential(request) do
      case request.options[:api_key] || Application.get_env(@otp_app, __MODULE__, [])[:api_key] do
        key when is_binary(key) -> key
        fun when is_function(fun, 0) -> fun.()
        {module, function, args} -> apply(module, function, args)
        nil ->
          raise "missing :api_key for \#{inspect(__MODULE__)} — set it in config " <>
                  "or pass `api_key:` to new/1, request/2 or a behaviour function"
      end
    end
    """
  end

  defp label(module) do
    module |> Module.split() |> List.last()
  end
end
