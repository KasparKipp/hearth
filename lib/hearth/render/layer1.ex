defmodule Hearth.Render.Layer1 do
  @moduledoc false

  # Renders the Layer 1 raw Req client — the module that holds the base
  # URL and assembles a configured `%Req.Request{}`. Layer 3 (the
  # behaviour implementation) dispatches through `client/1`.
  #
  # The credential is read from application config keyed by the client
  # module itself — `config :<otp_app>, <ClientModule>, api_key: "…"` —
  # with a `:api_key` option on `client/1` as a per-call override. The
  # config entry itself is wired by `mix hearth.install` / a later step;
  # this module only reads it.
  #
  # Auth is rendered from the spec's security scheme:
  #
  #   * `:bearer`               → `auth: {:bearer, credential}`
  #   * `{:api_key, :header, n}` → a request header
  #   * `{:api_key, :query, n}`  → a query parameter
  #   * `:none`                 → base URL only
  #   * `{:unsupported, type}`  → base URL only, plus a TODO comment
  #
  # Assembled as a string and run through `Code.format_string!/1`.

  alias Hearth.Spec.Auth

  @spec render(module(), atom(), String.t() | nil, Auth.strategy()) :: String.t()
  def render(module, otp_app, base_url, auth) do
    """
    defmodule #{inspect(module)} do
      @moduledoc \"\"\"
      Raw Req client for the #{label(module)} integration.

      Generated by Hearth. `client/1` returns a configured Req request —
      base URL from the OpenAPI spec, credential from application
      config. The behaviour implementation dispatches through it.
      \"\"\"

      @otp_app #{inspect(otp_app)}
      #{base_url_attr(base_url)}

      #{client_fun(auth)}#{credential_fun(auth)}
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  defp base_url_attr(nil) do
    ~s(# TODO: the spec declared no `servers` — set the API base URL.\n) <>
      ~s(  @base_url "https://api.example.com")
  end

  defp base_url_attr(url), do: ~s(@base_url #{inspect(url)})

  defp client_fun(:bearer) do
    """
    @doc "Builds a configured Req request — bearer auth from config."
    def client(opts \\\\ []) do
      Req.new(base_url: @base_url, auth: {:bearer, credential(opts)})
    end
    """
  end

  defp client_fun({:api_key, :header, name}) do
    """
    @doc "Builds a configured Req request — API-key header from config."
    def client(opts \\\\ []) do
      Req.new(base_url: @base_url, headers: [{#{inspect(name)}, credential(opts)}])
    end
    """
  end

  defp client_fun({:api_key, :query, name}) do
    """
    @doc "Builds a configured Req request — API-key query param from config."
    def client(opts \\\\ []) do
      Req.new(base_url: @base_url, params: %{#{inspect(name)} => credential(opts)})
    end
    """
  end

  defp client_fun(:none) do
    """
    @doc "Builds a configured Req request for the API."
    def client(_opts \\\\ []) do
      Req.new(base_url: @base_url)
    end
    """
  end

  defp client_fun({:unsupported, type}) do
    """
    # TODO: the spec uses #{inspect(type)} auth, which Hearth does not
    # generate automatically. Wire it as a Req request step — see
    # https://hexdocs.pm/req/Req.Steps.html
    @doc "Builds a configured Req request — auth not wired (see TODO above)."
    def client(_opts \\\\ []) do
      Req.new(base_url: @base_url)
    end
    """
  end

  defp credential_fun(:bearer), do: credential_helper()
  defp credential_fun({:api_key, _location, _name}), do: credential_helper()
  defp credential_fun(_auth), do: ""

  defp credential_helper do
    """

    defp credential(opts) do
      opts[:api_key] || Application.get_env(@otp_app, __MODULE__, [])[:api_key] ||
        raise "missing :api_key for \#{inspect(__MODULE__)} — set it in " <>
                "config or pass `api_key:` to client/1"
    end
    """
  end

  defp label(module) do
    module |> Module.split() |> List.last()
  end
end
