defmodule Hearth.Render.Layer1 do
  @moduledoc false

  # Renders the Layer 1 raw Req client. Its public API:
  #
  #   * `new/1`      — builds a configured `%Req.Request{}` (base URL,
  #                    auth, plus any passed opts), mirroring `Req.new/1`;
  #   * `request/2`  — performs a call, `{:ok, resp} | {:error, exc}`;
  #   * `request!/2` — same, raising on error.
  #
  # Layer 3 (the behaviour implementation) dispatches through
  # `request/2` — it never touches `new/1` or `Req` directly.
  #
  # The base URL (`Hearth.Render.BaseUrl`), the credential
  # (`Hearth.Render.Credential`) and the headers (`Hearth.Render.Headers`)
  # come from the entry's values (`Hearth.Spec.Values`): config, a
  # per-call option, or a resolver.
  #
  # Assembled as a string and run through `Code.format_string!/1`.

  alias Hearth.Render.BaseUrl
  alias Hearth.Render.Credential
  alias Hearth.Render.Values, as: RenderValues
  alias Hearth.Spec.Auth
  alias Hearth.Spec.Values

  # `opts`: `:prefixed` (`Hearth.Render.PrefixedIds`) and `:values`
  # (`Hearth.Spec.Values.parse/1` — the credential, the headers and the
  # base URL; today's defaults without it).
  @spec render(module(), atom(), String.t() | nil, String.t(), Auth.strategy(), keyword()) ::
          String.t()
  def render(module, otp_app, base_url, path_prefix, auth, opts \\ []) do
    prefixed = opts[:prefixed]
    values = opts[:values] || Values.default()
    %{credential: credential, headers: headers, base_url: base_url_from} = values

    """
    defmodule #{inspect(module)} do
      @moduledoc \"\"\"
      Raw Req client for the #{label(module)} integration.

      Generated by Hearth. `request/2` and `request!/2` perform calls
      against the API — #{BaseUrl.intro(base_url_from)}. `new/1`
      (mirroring `Req.new/1`) builds the underlying configured request.#{Credential.doc(module, otp_app, auth, credential)}#{Hearth.Render.Headers.doc(headers, otp_app, module)}#{BaseUrl.doc(base_url_from, BaseUrl.base_path(base_url, path_prefix))}
      \"\"\"

      #{otp_app_attr(otp_app, auth, values)}
      #{BaseUrl.attr(base_url, path_prefix, base_url_from)}

      #{new_fun(auth, values)}
      #{Hearth.Render.PrefixedIds.request_funs(prefixed) || request_funs()}#{BaseUrl.helper(base_url_from, BaseUrl.base_path(base_url, path_prefix))}#{Credential.step(auth, credential)}#{Hearth.Render.Headers.step(headers)}#{RenderValues.helpers(helper_values(auth, values))}#{Hearth.Render.PrefixedIds.layer1(prefixed)}
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end

  # Only when something reads config — nothing does when every value is
  # an option or a resolver.
  defp otp_app_attr(otp_app, auth, values) do
    reads_config? =
      not BaseUrl.step?(values.base_url) or
        Enum.any?(helper_values(auth, values), &match?({:config, _key}, &1))

    if reads_config?, do: "@otp_app #{inspect(otp_app)}", else: ""
  end

  # `new/1` registers the options the credential, headers and resolvers
  # read, prepends a step that resolves the base URL when it isn't the
  # spec's, and appends `put_api_key/1` / `put_headers/1`. With none of
  # that, the plain form.
  defp new_fun(auth, values) do
    keyed? = Auth.keyed?(auth)
    options = Values.options(values, keyed?)
    base_url_step? = BaseUrl.step?(values.base_url)

    steps =
      if(keyed?, do: ["put_api_key: &put_api_key/1"], else: []) ++
        if(values.headers == [], do: [], else: ["put_headers: &put_headers/1"])

    if options == [] and steps == [] and not base_url_step? do
      new_fun(auth)
    else
      accepts =
        if options == [],
          do: "",
          else:
            " Accepts `Req.new/1` options plus #{Enum.map_join(options, ", ", &"`#{inspect(&1)}`")}."

      """
      #{unsupported_todo(auth)}@doc "Builds a configured Req request#{auth_label(auth)}.#{accepts}"
      def new(opts \\\\ []) do
        #{if base_url_step?, do: "Req.new()", else: "Req.new(base_url: base_url())"}
        #{if options == [], do: "", else: "|> Req.Request.register_options(#{inspect(options)})"}
        #{if base_url_step?, do: "|> Req.Request.prepend_request_steps(resolve_base_url: &resolve_base_url/1)", else: ""}
        #{if steps == [], do: "", else: "|> Req.Request.append_request_steps(#{Enum.join(steps, ", ")})"}
        |> Req.merge(opts)
      end
      """
    end
  end

  defp helper_values(auth, values) do
    credential = if Auth.keyed?(auth), do: [values.credential], else: []
    credential ++ Enum.map(values.headers, &elem(&1, 1)) ++ [values.base_url]
  end

  defp auth_label(:bearer), do: " — bearer auth"
  defp auth_label(:basic), do: " — HTTP basic auth"
  defp auth_label({:api_key, :header, _name}), do: " — API-key header"
  defp auth_label({:api_key, :query, _name}), do: " — API-key query param"
  defp auth_label({:unsupported, _type}), do: " — auth not wired (see TODO above)"
  defp auth_label(:none), do: ""

  defp unsupported_todo({:unsupported, type}) do
    """
    # TODO: the spec uses #{inspect(type)} auth, which Hearth does not
    # generate automatically. Wire it as a Req request step — see
    # https://hexdocs.pm/req/Req.Steps.html
    """
  end

  defp unsupported_todo(_auth), do: ""

  defp new_fun(:none) do
    """
    @doc "Builds a configured Req request for the API."
    def new(opts \\\\ []) do
      Req.new(base_url: base_url()) |> Req.merge(opts)
    end
    """
  end

  defp new_fun({:unsupported, type}) do
    """
    # TODO: the spec uses #{inspect(type)} auth, which Hearth does not
    # generate automatically. Wire it as a Req request step — see
    # https://hexdocs.pm/req/Req.Steps.html
    @doc "Builds a configured Req request — auth not wired (see TODO above)."
    def new(opts \\\\ []) do
      Req.new(base_url: base_url()) |> Req.merge(opts)
    end
    """
  end

  defp request_funs do
    """
    @doc "Performs a request — returns `{:ok, response}` or `{:error, exception}`."
    def request(url, opts \\\\ []), do: Req.request(new(url: url), opts)

    @doc "Like `request/2`, but raises on error."
    def request!(url, opts \\\\ []), do: Req.request!(new(url: url), opts)
    """
  end

  defp label(module) do
    module |> Module.split() |> List.last()
  end
end
