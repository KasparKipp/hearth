defmodule Hearth.Render.MocksTest do
  use ExUnit.Case, async: true

  alias Hearth.Render.Mocks

  @mock MyApp.Integrations.Stripe.StripeApi.Mock
  @layer2 MyApp.Integrations.Stripe.StripeApi

  describe "defmock_line/2" do
    test "renders a Mox.defmock for the behaviour" do
      line = Mocks.defmock_line(@mock, @layer2)

      assert line ==
               "Mox.defmock(MyApp.Integrations.Stripe.StripeApi.Mock, " <>
                 "for: MyApp.Integrations.Stripe.StripeApi)"
    end
  end

  describe "render/2" do
    test "renders a header comment and one defmock" do
      source = Mocks.render(@mock, @layer2)

      assert source =~ "# Generated by Hearth"
      assert source =~ "Mox.defmock(MyApp.Integrations.Stripe.StripeApi.Mock,"
      assert source =~ "for: MyApp.Integrations.Stripe.StripeApi"
    end

    test "the rendered file is syntactically valid Elixir" do
      assert Code.string_to_quoted!(Mocks.render(@mock, @layer2))
    end
  end
end
